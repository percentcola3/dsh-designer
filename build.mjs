import {build} from 'esbuild-wasm';
import {readFile,readdir,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {dirname,join} from 'node:path';
// Package PDF.js's worker-side CMaps and standard fonts in the same local bundle.
// No asset URLs, CDN, blob Worker or runtime filesystem access are required.
export const pdfAssetsPlugin = {name:'designer-pdf-assets',setup(build){
  build.onResolve({filter:/^designer:pdf-assets$/},()=>({path:'pdf-assets',namespace:'designer-pdf'}));
  build.onLoad({filter:/.*/,namespace:'designer-pdf'},async()=>{
    const root=dirname(createRequire(import.meta.url).resolve('pdfjs-dist/package.json'));
    const assets={},notices=[];
    for(const directory of ['cmaps','standard_fonts']) {
      for(const name of (await readdir(join(root,directory))).sort()) {
        if(/\.(bcmap|pfb|ttf)$/.test(name)) assets[name]=(await readFile(join(root,directory,name))).toString('base64');
        else if(name.startsWith('LICENSE')) notices.push(await readFile(join(root,directory,name),'utf8'));
      }
    }
    const notice=notices.join('\n\n').replace(/\*\//g,'* /');
    return {contents:`/*! PDF.js bundled CMap/font notices\n${notice}\n*/\nexport default ${JSON.stringify(assets)};`,loader:'js'};
  });
}};
const result=await build({entryPoints:process.argv.includes('--pdf-check')?['ui/PDFView.jsx']:['client-entry.jsx'],bundle:true,loader:{'.md':'text','.css':'text','.txt':'text','.html':'text'},write:false,format:'cjs',platform:'browser',target:'es2022',external:['react','react-dom','@deepseek-ai/dsh-api-gateway/client','@deepseek-ai/dsh-client-ui-primitives'],jsxFactory:'React.createElement',jsxFragment:'React.Fragment',minify:false,legalComments:'eof',logLevel:'warning',plugins:[pdfAssetsPlugin]});
const text=`// Generated by npm run build; edit client-entry.jsx, ui/ and editor/ sources.\nwindow.__ModuleLoader__.load({id:'@local/dsh-designer',factory(require){\nconst module={exports:{}};const exports=module.exports;\n${result.outputFiles[0].text}\nreturn module.exports.default||module.exports;\n}});\n`;
if(!process.argv.includes('--check')&&!process.argv.includes('--pdf-check')) await writeFile('client.js',text,'utf8');
console.log(`${process.argv.includes('--check')||process.argv.includes('--pdf-check')?'Checked in memory':'Built installed'} Client module: ${(Buffer.byteLength(text)/1024).toFixed(0)} KiB; React remains external.`);
